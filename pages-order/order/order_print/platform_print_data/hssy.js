function dealAdress(adr) {
    var text = ""
    if (adr.length > 20) {
        text += `TEXT 1 0 184 816 ${adr.substring(0,19)}\r\n` + `TEXT 1 0 184 844 ${adr.substring(19,adr.length)}\r\n`
    } else {
        text += `TEXT 1 0 184 816 ${adr}\r\n`
    }
    return text
}

